"""Mirror every Claude skill into .agents/skills so Codex finds it, unless Codex has its own version.

Claude Code reads skills from .claude/skills; Codex reads .agents/skills. Each mirror is a single
SKILL.md: the Claude frontmatter, a short Codex note, then the Claude body word for word. Supporting
files (config.json and the like) stay in .claude/skills, where the skills already point, so any state
has exactly one copy.

A hand-written Codex version wins: put the line `<!-- codex-custom -->` in its SKILL.md and the sync
leaves that folder alone (a Codex-only skill works the same way). The marker must be explicit, because
the Codex desktop app's raw import writes unmarked copies that must be overwritten.

Agents are never copied: a Claude agent needs a real Codex port in .codex/agents (different tools and
hooks). The sync only lists Claude agents that have no port yet.

    just codex-skills-sync     # regenerate every mirror
    just codex-skills-check    # exit 1 if a mirror is missing, stale, or extra

Edit the Claude skill, never a generated mirror.
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = REPO_ROOT / ".claude" / "skills"
MIRROR_DIR = REPO_ROOT / ".agents" / "skills"
CLAUDE_AGENTS_DIR = REPO_ROOT / ".claude" / "agents"
CODEX_AGENTS_DIR = REPO_ROOT / ".codex" / "agents"
CUSTOM_MARKER = "<!-- codex-custom -->"
# Claude agent name -> Codex agent name, once a hand-written port exists in .codex/agents.
CODEX_AGENTS: dict[str, str] = {"committer": "committer", "pr-manager": "pr_manager"}

CODEX_NOTE_LINES = (
    "<!-- Generated by scripts/sync_codex_skills.py from .claude/skills/{name}/SKILL.md."
    " Edit that file, then run `just codex-skills-sync`. -->",
    "",
    "> **Codex note.** This skill was written for Claude Code. Follow it as written, with these"
    " translations:",
    ">",
    "> - Supporting files stay in `.claude/skills/{name}/`; read and write them there, never a copy.",
    "> - `mcp__<server>__<tool>` is the `<tool>` tool on the `<server>` MCP server (for example"
    " `mcp__anki__add_note` is `add_note` on `anki`).",
    "> - `mcp__claude_ai_<Service>__...` tools are claude.ai connectors that Codex does not have. If the"
    " skill needs one, say so and stop.",
    "{agents_line}",
    "> - `AskUserQuestion` means ask in chat, `WebFetch` and `WebSearch` mean Codex's web tools if"
    " enabled, and the `Agent` tool means delegating to a Codex agent.",
)


def agents_line(codex_agents: dict[str, str]) -> str:
    if codex_agents:
        pairs = ", ".join(f"`{claude}` is `{codex}`" for claude, codex in codex_agents.items())
        return f"> - Claude subagents are the Codex agents in `.codex/agents/`: {pairs}."
    return (
        "> - Claude subagents in `.claude/agents/` have no Codex port in this repo; do the subagent's job"
        " yourself by following its `.claude/agents/<name>.md`."
    )


def split_frontmatter(text: str) -> tuple[str, str]:
    if not text.startswith("---\n"):
        raise ValueError("SKILL.md must start with a --- frontmatter block")
    end = text.index("\n---\n", 4) + len("\n---\n")
    return text[:end], text[end:]


def render_mirror(name: str, source_text: str) -> str:
    frontmatter, body = split_frontmatter(source_text.replace("\r\n", "\n"))
    note = "\n".join(CODEX_NOTE_LINES).format(name=name, agents_line=agents_line(CODEX_AGENTS))
    return f"{frontmatter}\n{note}\n\n{body.lstrip(chr(10))}"


def custom_skills(mirror_dir: Path) -> set[str]:
    """Skill folders holding a hand-written Codex version, which the sync never touches."""
    if not mirror_dir.exists():
        return set()
    return {
        skill.parent.name
        for skill in mirror_dir.glob("*/SKILL.md")
        if CUSTOM_MARKER in skill.read_text(encoding="utf-8")
    }


def expected_mirrors(source_dir: Path, mirror_dir: Path) -> dict[Path, str]:
    custom = custom_skills(mirror_dir)
    return {
        mirror_dir / skill.parent.name / "SKILL.md": render_mirror(
            skill.parent.name, skill.read_text(encoding="utf-8")
        )
        for skill in sorted(source_dir.glob("*/SKILL.md"))
        if skill.parent.name not in custom
    }


def problems(source_dir: Path, mirror_dir: Path) -> list[str]:
    expected = expected_mirrors(source_dir, mirror_dir)
    custom = custom_skills(mirror_dir)
    found = []
    for path, content in expected.items():
        if not path.exists():
            found.append(f"missing: {path.relative_to(mirror_dir).as_posix()}")
        elif path.read_text(encoding="utf-8").replace("\r\n", "\n") != content:
            found.append(f"stale: {path.relative_to(mirror_dir).as_posix()}")
    if mirror_dir.exists():
        for path in sorted(mirror_dir.rglob("*")):
            relative = path.relative_to(mirror_dir)
            if path.is_file() and path not in expected and relative.parts[0] not in custom:
                found.append(f"extra: {relative.as_posix()}")
    return found


def sync(source_dir: Path, mirror_dir: Path) -> list[str]:
    """Update changed mirrors; delete anything else except hand-written Codex versions."""
    expected = expected_mirrors(source_dir, mirror_dir)
    generated_dirs = {path.parent for path in expected}
    custom_dirs = {mirror_dir / name for name in custom_skills(mirror_dir)}
    if mirror_dir.exists():
        for child in mirror_dir.iterdir():
            if child.is_dir() and child not in generated_dirs | custom_dirs:
                shutil.rmtree(child)
            elif child.is_file():
                child.unlink()
        for skill_dir in generated_dirs & set(mirror_dir.iterdir()):
            for leftover in skill_dir.rglob("*"):
                if leftover.is_file() and leftover not in expected:
                    leftover.unlink()
    for path, content in expected.items():
        if path.exists() and path.read_bytes() == content.encode("utf-8"):
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
    return [path.parent.name for path in expected]


def missing_agent_ports(claude_agents_dir: Path, codex_agents_dir: Path) -> list[str]:
    """Claude agents with no hand-ported `.codex/agents/<name>.toml`; reported, never copied."""
    return [
        agent.stem
        for agent in sorted(claude_agents_dir.glob("*.md"))
        if not (codex_agents_dir / f"{agent.stem}.toml").exists()
    ]


def print_notes() -> None:
    custom = sorted(custom_skills(MIRROR_DIR))
    if custom:
        print(f"kept hand-written Codex versions: {', '.join(custom)}")
    unported = missing_agent_ports(CLAUDE_AGENTS_DIR, CODEX_AGENTS_DIR)
    if unported:
        print(
            f"note: Claude agents without a Codex port (port by hand if wanted): {', '.join(unported)}"
        )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--check", action="store_true", help="report drift and exit 1 instead of writing"
    )
    args = parser.parse_args(argv)
    if args.check:
        found = problems(SOURCE_DIR, MIRROR_DIR)
        for line in found:
            print(line)
        print_notes()
        if found:
            print("run `just codex-skills-sync` to regenerate the Codex skill mirrors")
            return 1
        print("Codex skill mirrors are in sync")
        return 0
    names = sync(SOURCE_DIR, MIRROR_DIR)
    print(f"mirrored {len(names)} skills into .agents/skills: {', '.join(names)}")
    print_notes()
    return 0


if __name__ == "__main__":
    sys.exit(main())
